"""Five-bath particle-hole-symmetric ED-DMFT observable regeneration.

Bath-fit checkpoint parameters are Hamiltonian inputs.  Impurity diagonalization,
Green functions, self-energies, lattice spectra, observables, markers, and
robustness sweeps are regenerated by this module.
"""
from __future__ import annotations

from functools import lru_cache
from itertools import combinations
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from common import completion_curve, completion_marker, minus_dfermi_domega
from common import write_json

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "inputs" / "five_bath_ed_dmft" / "bath_fit_checkpoint.csv"
RESULTS = ROOT / "results"
OUT = RESULTS / "five_bath_ed_dmft"
DETAIL = RESULTS / "five_bath_ed_dmft_detail"
NSITES = 6


@lru_cache(maxsize=None)
def _basis(n_up: int, n_down: int) -> tuple[int, ...]:
    states: list[int] = []
    for ups in combinations(range(NSITES), int(n_up)):
        upbits = sum(1 << i for i in ups)
        for dns in combinations(range(NSITES), int(n_down)):
            states.append(upbits + sum(1 << (NSITES + i) for i in dns))
    return tuple(states)


def _popbelow(state: int, orbital: int) -> int:
    return (state & ((1 << orbital) - 1)).bit_count()


def _annihilate(state: int, orbital: int):
    if not ((state >> orbital) & 1):
        return None
    return state ^ (1 << orbital), (-1.0 if _popbelow(state, orbital) % 2 else 1.0)


def _create(state: int, orbital: int):
    if (state >> orbital) & 1:
        return None
    return state ^ (1 << orbital), (-1.0 if _popbelow(state, orbital) % 2 else 1.0)


def _hamiltonian(row: pd.Series, n_up: int, n_down: int) -> tuple[tuple[int, ...], np.ndarray]:
    basis = _basis(n_up, n_down); index = {state: i for i, state in enumerate(basis)}
    h = np.zeros((len(basis), len(basis)), dtype=float)
    U = float(row.U)
    energies = [0.0, 0.0, float(row.e1), -float(row.e1), float(row.e2), -float(row.e2)]
    hyb = [0.0, float(row.V0), float(row.V1), float(row.V1), float(row.V2), float(row.V2)]
    for j, state in enumerate(basis):
        n0u = (state >> 0) & 1; n0d = (state >> NSITES) & 1
        diag = U * (n0u - 0.5) * (n0d - 0.5)
        for site in range(1, NSITES):
            diag += energies[site] * (((state >> site) & 1) + ((state >> (NSITES + site)) & 1))
        h[j, j] = diag
        for spin_offset in (0, NSITES):
            imp = spin_offset
            for site in range(1, NSITES):
                bath = spin_offset + site; v = hyb[site]
                a = _annihilate(state, bath)
                if a is not None:
                    s1, sg1 = a; c = _create(s1, imp)
                    if c is not None:
                        s2, sg2 = c; h[index[s2], j] += v * sg1 * sg2
                a = _annihilate(state, imp)
                if a is not None:
                    s1, sg1 = a; c = _create(s1, bath)
                    if c is not None:
                        s2, sg2 = c; h[index[s2], j] += v * sg1 * sg2
    return basis, h


def _operator_vector(basis_from, vector_from, basis_to, orbital: int, creation: bool) -> np.ndarray:
    index = {state: i for i, state in enumerate(basis_to)}
    out = np.zeros(len(basis_to), dtype=complex)
    for j, state in enumerate(basis_from):
        result = _create(state, orbital) if creation else _annihilate(state, orbital)
        if result is None:
            continue
        state2, sign = result; out[index[state2]] += sign * vector_from[j]
    return out


def _lehmann_data(row: pd.Series) -> dict[str, Any]:
    b0, h0 = _hamiltonian(row, 3, 3); e0, v0 = np.linalg.eigh(h0)
    bm, hm = _hamiltonian(row, 2, 3); em, vm = np.linalg.eigh(hm)
    bp, hp = _hamiltonian(row, 4, 3); ep, vp = np.linalg.eigh(hp)
    ground = v0[:, 0]; eg = float(e0[0])
    vec_m = _operator_vector(b0, ground, bm, 0, creation=False)
    vec_p = _operator_vector(b0, ground, bp, 0, creation=True)
    weight_m = np.abs(vm.conj().T @ vec_m) ** 2
    weight_p = np.abs(vp.conj().T @ vec_p) ** 2
    return {"eg": eg, "em": em, "ep": ep, "wm": weight_m, "wp": weight_p}


def _green_sigma(row: pd.Series, leh: dict[str, Any], omega: np.ndarray, eta: float) -> tuple[np.ndarray, np.ndarray]:
    z = np.asarray(omega, dtype=float) + 1j * float(eta)
    eg = leh["eg"]
    G = np.sum(leh["wp"][:, None] / (z[None, :] + eg - leh["ep"][:, None]), axis=0)
    G += np.sum(leh["wm"][:, None] / (z[None, :] - eg + leh["em"][:, None]), axis=0)
    delta = float(row.V0)**2 / z
    for v, e in ((float(row.V1), float(row.e1)), (float(row.V2), float(row.e2))):
        delta += v*v/(z-e) + v*v/(z+e)
    sigma = z - delta - 1.0 / G
    return G, sigma


def _square_local_spectrum(omega: np.ndarray, sigma: np.ndarray, eta: float, nk: int) -> np.ndarray:
    k = np.linspace(-np.pi, np.pi, int(nk), endpoint=False)
    eps = -2.0 * (np.cos(k)[:, None] + np.cos(k)[None, :])
    accum = np.zeros(len(omega), dtype=complex)
    # Chunk omega to keep peak memory small.
    for start in range(0, len(omega), 160):
        stop = min(start + 160, len(omega))
        z = omega[start:stop][None, None, :] + 1j * float(eta)
        g = 1.0 / (z - eps[:, :, None] - sigma[start:stop][None, None, :])
        accum[start:stop] = np.mean(g, axis=(0, 1))
    return -np.imag(accum) / np.pi


def _readouts(omega: np.ndarray, A: np.ndarray, temperature: float, wmin: float, wmax: float) -> tuple[float, float, float, float]:
    dw = float(omega[1] - omega[0])
    le = float(np.sum(A * minus_dfermi_domega(omega, float(temperature))) * dw)
    mask = (np.abs(omega) >= float(wmin)) & (np.abs(omega) <= float(wmax))
    he = float(np.sum(A[mask]) * dw)
    a0 = float(A[int(np.argmin(np.abs(omega)))])
    sumrule = float(np.trapz(A, omega))
    return le, he, a0, sumrule


def _pole_diagnostics(omega: np.ndarray, sigma: np.ndarray, previous: float | None = None) -> tuple[float, float]:
    """Track the inner finite-energy positive-frequency self-energy pole.

    The diagnostic deliberately excludes the incipient near-zero branch and
    follows the lowest-energy local maximum in the finite-energy pole sector.
    At U=0 the self-energy is numerically zero and no pole is reported.
    """
    del previous
    y = -np.imag(sigma)
    mask = (omega >= 1.5) & (omega <= 3.0)
    inds = np.where(mask)[0]
    candidates = [idx for idx in inds[1:-1] if y[idx] >= y[idx-1] and y[idx] >= y[idx+1]]
    if not candidates:
        return float("nan"), float("nan")
    candidates = [idx for idx in candidates if y[idx] > 1e-8]
    if not candidates:
        return float("nan"), float("nan")
    idx = int(min(candidates, key=lambda i: float(omega[i])))
    return float(omega[idx]), float(y[idx] / np.pi)


def _z_proxy(row: pd.Series, leh: dict[str, Any], wn: float) -> float:
    z = np.asarray([0.0], dtype=float)
    _, sigma = _green_sigma(row, leh, z, float(wn))
    return float(1.0 / (1.0 - np.imag(sigma[0]) / float(wn)))


def _markers(frame: pd.DataFrame, fractions: list[float], endpoint: float) -> pd.DataFrame:
    sub = frame[frame.U <= endpoint + 1e-12].sort_values("U")
    u = sub.U.to_numpy(float); le = sub.LE.to_numpy(float); he = sub.HE.to_numpy(float)
    rows = []
    for q in fractions:
        ule = completion_marker(le, u, float(q)); uhe = completion_marker(he, u, float(q))
        rows.append({"fraction": float(q), "U_LE": ule, "U_HE": uhe, "HE_minus_LE": uhe-ule, "ordering": "HE<LE" if uhe < ule else "LE<=HE"})
    return pd.DataFrame(rows)


def generate(config: dict[str, Any]) -> list[Path]:
    cfg = config["five_bath_ed_dmft"]
    checkpoint = pd.read_csv(INPUT).sort_values("U")
    if not checkpoint["converged"].astype(bool).all():
        raise ValueError("Canonical five-bath input deck must contain only converged checkpoints")
    if float(checkpoint.U.max()) != float(cfg["primary_endpoint"]):
        raise ValueError("Input deck endpoint and configured primary endpoint disagree")
    OUT.mkdir(parents=True, exist_ok=True); DETAIL.mkdir(parents=True, exist_ok=True)
    omega = np.linspace(-float(cfg["wmax"]), float(cfg["wmax"]), int(cfg["nw"]))
    lehm: dict[float, dict[str, Any]] = {}
    for row in checkpoint.itertuples(index=False):
        lehm[float(row.U)] = _lehmann_data(pd.Series(row._asdict()))

    baseline_eta = float(cfg["baseline_broadening"])
    spectra_by_u: dict[float, tuple[np.ndarray, np.ndarray]] = {}
    base_rows = []
    previous_pole: float | None = None
    for row_tuple in checkpoint.itertuples(index=False):
        row = pd.Series(row_tuple._asdict()); U = float(row.U); leh = lehm[U]
        _, sigma = _green_sigma(row, leh, omega, baseline_eta)
        A = _square_local_spectrum(omega, sigma, baseline_eta, int(cfg["nk"]))
        le, he, a0, sumrule = _readouts(omega, A, float(cfg["readout_temperature"]), *map(float, cfg["baseline_high_energy_window"]))
        pole_energy, pole_height = _pole_diagnostics(omega, sigma, previous_pole)
        previous_pole = pole_energy
        z_proxy = _z_proxy(row, leh, float(cfg["z_imaginary_frequency"]))
        base_rows.append({
            "U": U, "LE": le, "HE": he, "Z": z_proxy, "pole_energy": pole_energy, "pole_height": pole_height,
            "A0": a0, "sumrule": sumrule, "iterations": int(row.iterations), "converged": bool(row.converged),
            "param_change": float(row.param_change), "fit_error": float(row.fit_error), "sc_residual": float(row.sc_residual),
        })
        spectra_by_u[U] = (A, sigma)
    curves = pd.DataFrame(base_rows).sort_values("U")
    curves["LE_completion"] = completion_curve(curves.LE.to_numpy(float))
    curves["HE_completion"] = completion_curve(curves.HE.to_numpy(float))
    markers = _markers(curves, [float(q) for q in config["markers"]["fractions"]], float(cfg["primary_endpoint"]))

    # Representative spectral snapshots from regenerated Hamiltonian solutions.
    spectral_rows = []
    for U in cfg["representative_interactions"]:
        A, sigma = spectra_by_u[float(U)]
        for w, av, sv in zip(omega, A, sigma):
            spectral_rows.append({"U": float(U), "omega": float(w), "A": float(av), "ReSigma": float(np.real(sv)), "ImSigma": float(np.imag(sv))})
    spectra = pd.DataFrame(spectral_rows)

    # Observable-window/broadening robustness, all regenerated from ED.
    robust_rows = []
    for eta in cfg["robustness_broadenings"]:
        per_u: dict[float, np.ndarray] = {}
        for row_tuple in checkpoint.itertuples(index=False):
            row = pd.Series(row_tuple._asdict()); U = float(row.U)
            _, sigma = _green_sigma(row, lehm[U], omega, float(eta))
            per_u[U] = _square_local_spectrum(omega, sigma, float(eta), int(cfg["robustness_nk"]))
        for window in cfg["robustness_windows"]:
            vals = []
            for row_tuple in checkpoint.itertuples(index=False):
                U = float(row_tuple.U); A = per_u[U]
                le, he, _, _ = _readouts(omega, A, float(cfg["readout_temperature"]), float(window["wmin"]), float(window["wmax"]))
                vals.append((U, le, he))
            vv = pd.DataFrame(vals, columns=["U","LE","HE"])
            # Monotonicity is reported as net variation / total step variation.
            def mono(y):
                y=np.asarray(y,float); steps=np.diff(y); total=float(np.sum(np.abs(steps))); return abs(float(y[-1]-y[0]))/total if total>1e-30 else 1.0
            for q in config["markers"]["fractions"]:
                ule = completion_marker(vv.LE.to_numpy(float), vv.U.to_numpy(float), float(q))
                uhe = completion_marker(vv.HE.to_numpy(float), vv.U.to_numpy(float), float(q))
                robust_rows.append({"eta": float(eta), "window": str(window["id"]), "wmin": float(window["wmin"]), "wmax": float(window["wmax"]), "fraction": float(q), "U_LE": ule, "U_HE": uhe, "HE_minus_LE": uhe-ule, "ordering": "HE<LE" if uhe < ule else "LE<=HE", "LE_monotonicity": mono(vv.LE), "HE_monotonicity": mono(vv.HE)})
    robust = pd.DataFrame(robust_rows)

    endpoint_rows = []
    for endpoint in cfg["endpoint_audit"]:
        mm = _markers(curves, [float(q) for q in config["markers"]["fractions"]], float(endpoint))
        for row in mm.itertuples(index=False):
            endpoint_rows.append({"Umax": float(endpoint), "fraction": float(row.fraction), "U_LE": float(row.U_LE), "U_HE": float(row.U_HE), "delta": float(row.HE_minus_LE), "ordering": str(row.ordering)})
    endpoints = pd.DataFrame(endpoint_rows)

    # The exact Hamiltonian input deck is copied into results for provenance/figure diagnostics.
    bath_out = checkpoint[["U","V0","V1","V2","e1","e2"]].copy()
    diagnostics = checkpoint.copy()

    outputs = [
        OUT/"five_bath_dmft_curves.csv", OUT/"five_bath_dmft_markers.csv", OUT/"five_bath_readout_robustness.csv",
        DETAIL/"endpoint_robustness.csv", DETAIL/"five_bath_dmft_bath.csv", DETAIL/"five_bath_dmft_spectra.csv",
        DETAIL/"five_bath_solver_diagnostics.csv", DETAIL/"five_bath_generation.json",
    ]
    curves.to_csv(outputs[0], index=False); markers.to_csv(outputs[1], index=False); robust.to_csv(outputs[2], index=False)
    endpoints.to_csv(outputs[3], index=False); bath_out.to_csv(outputs[4], index=False); spectra.to_csv(outputs[5], index=False)
    diagnostics.to_csv(outputs[6], index=False)
    write_json(outputs[7], {
        "generator": "src/five_bath_ed.py", "input_deck": str(INPUT.relative_to(ROOT)).replace('\\','/'),
        "primary_interaction_range": [float(checkpoint.U.min()), float(checkpoint.U.max())],
        "all_input_checkpoints_converged": bool(checkpoint.converged.astype(bool).all()),
        "impurity_observables_regenerated_from_hamiltonian": True, "precomputed_spectra_or_markers_consumed": False,
        "bath_fit_optimizer_rerun": False,
        "bath_fit_boundary": "explicit converged bath-parameter checkpoint plus stored fit/self-consistency diagnostics",
        "robustness_case_count": int(len(robust)), "endpoint_case_count": int(len(endpoints)),
    })
    return outputs
