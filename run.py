"""Canonical reproduction driver for the crossover-ordering analysis.

A fresh run starts from an empty ``results/`` tree.  The controlled pole family
is regenerated directly from its declared self-energy equations.  The five-bath
validation is regenerated by exact diagonalization from the explicit converged
bath-fit input deck.  Two-site-DMFT and matched electronic-evolution comparison calculations
are then regenerated in isolated child processes.  No precomputed spectra,
self-energies, observables, or crossover markers are staged as calculation inputs.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
import platform
import shutil
import subprocess
import sys
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
RECEIPT_PATH = RESULTS / "run_receipt.json"
MANIFEST_PATH = RESULTS / "manifest.json"
CONFIG_PATH = ROOT / "inputs" / "config.json"
TRANSACTION_ROOT = ROOT / ".stepwise_transaction"

PHASES = [
    "generate_pole_kinematics",
    "generate_five_bath_ed_dmft",
    "two_site_square",
    "two_site_anisotropic",
    "two_site_merge",
    "two_site_convergence_0",
    "two_site_convergence_1",
    "two_site_convergence_merge",
    "two_site_broadening_0",
    "two_site_broadening_1",
    "two_site_broadening_2",
    "two_site_broadening_merge",
    "two_site_high_energy_square",
    "two_site_high_energy_anisotropic",
    "two_site_high_energy_merge",
    "path_discrimination",
    "summaries",
    "revision_validation",
]


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _environment_metadata() -> dict[str, Any]:
    package_versions: dict[str, str] = {}
    for package in ("numpy", "pandas", "matplotlib", "scipy"):
        try:
            package_versions[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            package_versions[package] = "not-installed"
    thread_variables = {
        name: os.environ.get(name)
        for name in (
            "OMP_NUM_THREADS",
            "OPENBLAS_NUM_THREADS",
            "MKL_NUM_THREADS",
            "NUMEXPR_NUM_THREADS",
        )
    }
    return {
        "python_version": platform.python_version(),
        "python_implementation": platform.python_implementation(),
        "platform": platform.platform(),
        "system": platform.system(),
        "release": platform.release(),
        "machine": platform.machine(),
        "package_versions": package_versions,
        "thread_environment": thread_variables,
    }


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        json.dump(data, handle, indent=2, sort_keys=True)
        handle.write("\n")


def _result_files() -> list[Path]:
    if not RESULTS.exists():
        return []
    return sorted(
        path
        for path in RESULTS.rglob("*")
        if path.is_file()
        and path.suffix.lower() in {".csv", ".json"}
        and path not in {RECEIPT_PATH, MANIFEST_PATH}
    )


def _snapshot() -> dict[str, str]:
    return {
        str(path.relative_to(ROOT)).replace("\\", "/"): _sha256(path)
        for path in _result_files()
    }


def _changed_outputs(before: dict[str, str], after: dict[str, str]) -> list[dict[str, Any]]:
    changed: list[dict[str, Any]] = []
    for relative_path, digest in sorted(after.items()):
        if before.get(relative_path) == digest:
            continue
        path = ROOT / relative_path
        changed.append(
            {
                "path": relative_path,
                "bytes": path.stat().st_size,
                "sha256": digest,
                "change": "created" if relative_path not in before else "modified",
            }
        )
    for relative_path, digest in sorted(before.items()):
        if relative_path in after:
            continue
        changed.append(
            {
                "path": relative_path,
                "bytes": 0,
                "sha256": digest,
                "change": "deleted",
            }
        )
    return changed


def _clear_generated_results() -> None:
    if TRANSACTION_ROOT.exists():
        shutil.rmtree(TRANSACTION_ROOT)
    if RESULTS.exists():
        shutil.rmtree(RESULTS)
    RESULTS.mkdir(parents=True, exist_ok=True)



def _load_receipt() -> dict[str, Any]:
    if not RECEIPT_PATH.is_file():
        raise FileNotFoundError("No in-progress receipt exists. Start with --fresh.")
    return json.loads(RECEIPT_PATH.read_text(encoding="utf-8"))


def _latest_recorded_hashes(receipt: dict[str, Any]) -> dict[str, str]:
    expected: dict[str, str] = {}
    for record in receipt.get("phase_records", []):
        for output in record.get("outputs", []):
            path = str(output["path"])
            if output.get("change") == "deleted":
                expected.pop(path, None)
            else:
                expected[path] = str(output["sha256"])
    return expected


def _prepare_transaction(receipt: dict[str, Any], phase: str, index: int) -> None:
    if TRANSACTION_ROOT.exists():
        shutil.rmtree(TRANSACTION_ROOT)
    backup_root = TRANSACTION_ROOT / "checkpoint"
    before_hashes = _snapshot()
    for relative_path in before_hashes:
        source = ROOT / relative_path
        target = backup_root / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    receipt["active_transaction"] = {
        "phase": phase,
        "index": index,
        "state": "prepared",
        "prepared_at_utc": _utc_now(),
        "backup_root": str(backup_root.relative_to(ROOT)).replace("\\", "/"),
        "before_hashes": before_hashes,
    }
    _write_json(RECEIPT_PATH, receipt)


def _recover_active_transaction(receipt: dict[str, Any]) -> None:
    transaction = receipt.get("active_transaction")
    if not transaction:
        return
    state = str(transaction.get("state", "prepared"))
    phase = str(transaction.get("phase", "unknown"))
    index = int(transaction.get("index", 0))
    backup_root = ROOT / str(transaction.get("backup_root", ""))
    if state == "committed":
        if TRANSACTION_ROOT.exists():
            shutil.rmtree(TRANSACTION_ROOT)
        receipt.pop("active_transaction", None)
        _write_json(RECEIPT_PATH, receipt)
        return
    expected = {str(path): str(digest) for path, digest in transaction.get("before_hashes", {}).items()}
    for path in _result_files():
        path.unlink()
    if backup_root.is_dir():
        for source in sorted(backup_root.rglob("*")):
            if not source.is_file():
                continue
            relative = source.relative_to(backup_root)
            target = ROOT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    if _snapshot() != expected:
        raise ValueError(f"Rollback verification failed for interrupted phase {phase}")
    receipt.setdefault("transaction_recoveries", []).append(
        {
            "phase": phase,
            "index": index,
            "recovered_at_utc": _utc_now(),
            "reason": "uncommitted phase output detected after external interruption",
        }
    )
    receipt.pop("active_transaction", None)
    if TRANSACTION_ROOT.exists():
        shutil.rmtree(TRANSACTION_ROOT)
    _write_json(RECEIPT_PATH, receipt)


def _commit_transaction(receipt: dict[str, Any]) -> None:
    transaction = receipt.get("active_transaction")
    if not transaction:
        raise RuntimeError("No active phase transaction to commit")
    transaction["state"] = "committed"
    transaction["committed_at_utc"] = _utc_now()
    _write_json(RECEIPT_PATH, receipt)
    if TRANSACTION_ROOT.exists():
        shutil.rmtree(TRANSACTION_ROOT)
    receipt.pop("active_transaction", None)


def _verify_checkpoint(receipt: dict[str, Any]) -> None:
    _recover_active_transaction(receipt)
    if receipt.get("execution_mode") != "stepwise-full":
        raise ValueError("Existing receipt is not a stepwise-full run")
    if not receipt.get("fresh_run") or not receipt.get("started_from_empty"):
        raise ValueError("Only a run that started from an empty results tree can continue")
    if receipt.get("status") not in {"in_progress", "interrupted"}:
        raise ValueError(f"Receipt status is not continuable: {receipt.get('status')}")
    completed = int(receipt.get("phases_completed", 0))
    records = receipt.get("phase_records", [])
    if completed != len(records):
        raise ValueError("Receipt phase count is inconsistent")
    for index, record in enumerate(records, start=1):
        if record.get("index") != index or record.get("phase") != PHASES[index - 1]:
            raise ValueError("Receipt phase order is inconsistent")
        if int(record.get("return_code", 1)) != 0:
            raise ValueError("A completed receipt phase has a nonzero return code")
    for relative_path, digest in _latest_recorded_hashes(receipt).items():
        path = ROOT / relative_path
        if not path.is_file() or _sha256(path) != digest:
            raise ValueError(f"Checkpoint output changed or is missing: {relative_path}")


def _build_manifest(execution_mode: str) -> dict[str, Any]:
    # The receipt is finalized *after* this manifest is verified. Hashing it here
    # would invalidate the manifest as soon as manifest_verified is recorded.
    # Track immutable result files only; validate run_receipt.json separately.
    files = _result_files()
    manifest = {
        "configuration": str(CONFIG_PATH.relative_to(ROOT)).replace("\\", "/"),
        "execution": execution_mode,
        "files": [
            {
                "path": str(path.relative_to(ROOT)).replace("\\", "/"),
                "bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
            for path in files
        ],
    }
    _write_json(MANIFEST_PATH, manifest)
    return manifest


def _verify_manifest(manifest: dict[str, Any]) -> bool:
    # Detect missing/extra scientific output entries as well as hash mismatches.
    expected = {str(p.relative_to(ROOT)).replace("\\", "/") for p in _result_files()}
    recorded = [entry.get("path") for entry in manifest.get("files", [])]
    if len(recorded) != len(set(recorded)) or set(recorded) != expected:
        return False
    for entry in manifest.get("files", []):
        path = ROOT / entry["path"]
        if not path.is_file() or path.stat().st_size != int(entry["bytes"]) or _sha256(path) != entry["sha256"]:
            return False
    return True


def _run_phase_worker(phase: str) -> None:
    sys.path.insert(0, str(ROOT / "src"))
    from pipeline import run_phase  # imported only in child workers
    from common import load_json

    if phase == "revision_validation":
        from revision_validation import main as run_review_validation
        run_review_validation()
    else:
        run_phase(phase, load_json(CONFIG_PATH))


def _new_receipt() -> dict[str, Any]:
    _clear_generated_results()
    receipt: dict[str, Any] = {
        "run_id": str(uuid.uuid4()),
        "execution_mode": "stepwise-full",
        "fresh_run": True,
        "started_from_empty": True,
        "fresh_run_scope": "results/ is cleared completely; controlled pole-family results are regenerated from equations; five-bath ED-DMFT observables are regenerated from the declared bath-fit input deck; two-site-DMFT and matched electronic-evolution comparison outputs are regenerated",
        "primitive_input_boundary": "five-bath bath-fit checkpoint parameters and diagnostics; no precomputed spectra/observables/markers",
        "checkpoint_continuations": 0,
        "cache_reused": False,
        "fallback_used": False,
        "transactional_phases": True,
        "transaction_recoveries": [],
        "configuration": str(CONFIG_PATH.relative_to(ROOT)).replace("\\", "/"),
        "environment": _environment_metadata(),
        "started_at_utc": _utc_now(),
        "phases_expected": len(PHASES),
        "phases_completed": 0,
        "failed_phases": [],
        "phase_records": [],
        "invocations": [],
        "status": "in_progress",
        "elapsed_phase_seconds": 0.0,
    }
    _write_json(RECEIPT_PATH, receipt)
    return receipt


def _finalize(receipt: dict[str, Any]) -> None:
    execution = "fresh isolated-phase pipeline with equation-generated pole family and Hamiltonian-regenerated five-bath ED observables"
    manifest = _build_manifest(execution)
    verified = _verify_manifest(manifest)
    receipt.update(
        {
            "status": "completed" if verified else "failed_manifest_verification",
            "finished_at_utc": _utc_now(),
            "all_return_codes_zero": True,
            "all_declared_phases_completed": True,
            "manifest_verified": bool(verified),
        }
    )
    _write_json(RECEIPT_PATH, receipt)
    if not verified:
        raise RuntimeError("Generated results manifest failed verification")


def _run_stepwise_full(*, fresh: bool, continue_run: bool, max_phases: int | None) -> None:
    if fresh and continue_run:
        raise ValueError("Choose either --fresh or --continue-run, not both")
    if continue_run:
        receipt = _load_receipt()
        _verify_checkpoint(receipt)
        receipt["checkpoint_continuations"] = int(receipt.get("checkpoint_continuations", 0)) + 1
    else:
        receipt = _new_receipt()

    start_index = int(receipt.get("phases_completed", 0))
    if start_index >= len(PHASES):
        if receipt.get("status") != "completed":
            _finalize(receipt)
        print("All declared phases are already complete.")
        return

    remaining = len(PHASES) - start_index
    count = remaining if max_phases is None else min(max_phases, remaining)
    if count < 1:
        raise ValueError("--max-phases must be at least 1")

    child_env = os.environ.copy()
    child_env.setdefault("OMP_NUM_THREADS", "1")
    child_env.setdefault("OPENBLAS_NUM_THREADS", "1")
    child_env.setdefault("MKL_NUM_THREADS", "1")
    child_env.setdefault("NUMEXPR_NUM_THREADS", "1")

    for previous in receipt.get("invocations", []):
        if previous.get("status") == "in_progress":
            previous["status"] = "interrupted_external"
            previous["recovered_at_utc"] = _utc_now()

    invocation = {
        "invocation_id": len(receipt.get("invocations", [])) + 1,
        "started_at_utc": _utc_now(),
        "start_phase_index": start_index + 1,
        "end_phase_index": start_index,
        "requested_phase_count": count,
        "completed_phase_count": 0,
        "continuation": bool(continue_run),
        "status": "in_progress",
        "elapsed_seconds": 0.0,
    }
    receipt["invocations"].append(invocation)
    _write_json(RECEIPT_PATH, receipt)
    invocation_start = time.time()

    for zero_index in range(start_index, start_index + count):
        phase = PHASES[zero_index]
        index = zero_index + 1
        before = _snapshot()
        _prepare_transaction(receipt, phase, index)
        phase_start = time.time()
        print(f"=== Phase [{index}/{len(PHASES)}] {phase} ===", flush=True)
        completed = subprocess.run(
            [sys.executable, str(Path(__file__).resolve()), "--phase", phase],
            cwd=ROOT,
            env=child_env,
            check=False,
        )
        duration = time.time() - phase_start
        after = _snapshot()
        record = {
            "index": index,
            "phase": phase,
            "return_code": int(completed.returncode),
            "elapsed_seconds": duration,
            "outputs": _changed_outputs(before, after),
        }
        if completed.returncode != 0:
            receipt["failed_phases"].append(phase)
            receipt["status"] = "interrupted"
            receipt["last_error_return_code"] = int(completed.returncode)
            invocation.update(
                {
                    "finished_at_utc": _utc_now(),
                    "elapsed_seconds": time.time() - invocation_start,
                    "status": "failed",
                }
            )
            _recover_active_transaction(receipt)
            _write_json(RECEIPT_PATH, receipt)
            raise SystemExit(completed.returncode)

        receipt["phase_records"].append(record)
        receipt["phases_completed"] = index
        receipt["elapsed_phase_seconds"] = float(receipt.get("elapsed_phase_seconds", 0.0)) + duration
        receipt["status"] = "in_progress"
        invocation.update(
            {
                "end_phase_index": index,
                "completed_phase_count": index - start_index,
                "elapsed_seconds": time.time() - invocation_start,
                "last_phase": phase,
            }
        )
        _commit_transaction(receipt)
        _write_json(RECEIPT_PATH, receipt)
        print(f"=== Completed {phase} in {duration:.1f} s ===", flush=True)

    invocation.update(
        {
            "finished_at_utc": _utc_now(),
            "elapsed_seconds": time.time() - invocation_start,
            "status": "completed",
            "end_phase_index": int(receipt["phases_completed"]),
        }
    )

    if int(receipt["phases_completed"]) == len(PHASES):
        _finalize(receipt)
        print(f"Run receipt: {RECEIPT_PATH}")
        print(f"Manifest: {MANIFEST_PATH}")
        print(f"Completed all phases in {receipt['elapsed_phase_seconds']:.1f} phase-seconds")
    else:
        receipt["status"] = "in_progress"
        receipt["last_checkpoint_at_utc"] = _utc_now()
        _write_json(RECEIPT_PATH, receipt)
        next_phase = PHASES[int(receipt["phases_completed"])]
        print(
            f"Checkpoint saved after {receipt['phases_completed']}/{len(PHASES)} phases. "
            f"Continue with --continue-run; next phase: {next_phase}"
        )




def _run_figures() -> None:
    completed = subprocess.run(
        [sys.executable, str(ROOT / "src" / "figures.py")],
        cwd=ROOT,
        check=False,
    )
    if completed.returncode != 0:
        raise SystemExit(completed.returncode)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Reproduce the Paper9 numerical results and publication figures."
    )
    parser.add_argument(
        "task",
        nargs="?",
        choices=("all", "analysis", "figures"),
        default="all",
        help="all (default): analysis + figures; analysis: numerical pipeline only; figures: rebuild figures from existing results.",
    )
    parser.add_argument(
        "--phase",
        choices=tuple(PHASES),
        default=None,
        help=argparse.SUPPRESS,
    )
    parser.add_argument(
        "--fresh",
        action="store_true",
        help="Clear results/ and start a new verified numerical run.",
    )
    parser.add_argument(
        "--continue-run",
        action="store_true",
        help="Continue the same fresh run after checkpoint-hash verification.",
    )
    parser.add_argument(
        "--max-phases",
        type=int,
        default=None,
        help="Execute at most this many next numerical phases in the current invocation.",
    )
    parser.add_argument(
        "--step",
        action="store_true",
        help="Execute exactly one next numerical phase and save a verified checkpoint.",
    )
    args = parser.parse_args()

    if args.phase is not None:
        if args.task != "all" or args.fresh or args.continue_run or args.max_phases is not None or args.step:
            parser.error("--phase is an internal worker option and cannot be combined with other options")
        _run_phase_worker(args.phase)
        return

    if args.task == "figures":
        if args.fresh or args.continue_run or args.max_phases is not None or args.step:
            parser.error("figures cannot be combined with numerical-run checkpoint options")
        _run_figures()
        return

    max_phases = 1 if args.step else args.max_phases
    fresh = args.fresh or not args.continue_run
    _run_stepwise_full(fresh=fresh, continue_run=args.continue_run, max_phases=max_phases)

    if args.task == "all":
        receipt = _load_receipt()
        if receipt.get("status") == "completed":
            _run_figures()
        else:
            print("Figures deferred until the numerical pipeline reaches completed status.")


if __name__ == "__main__":
    main()
